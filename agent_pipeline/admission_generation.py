"""Generate and drift-check call admission data from explicit pinned inputs.

``SyzkallerCallTable`` is an explicit trusted export of the supplied build.
This module verifies and binds that export; it does not derive the table from
syzkaller source or binaries.  A production call-table exporter is outside
this patch.
"""

from __future__ import annotations

import hashlib
import os
import re
import stat
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import TypeVar

from pydantic import BaseModel, Field, model_validator

from .admission import (
    AdmissionLimits,
    AuthorityRecord,
    CallAdmissionEntry,
    CallAdmissionProfile,
    SyzkallerBuildManifest,
    SyzkallerCallTable,
    SyzkallerTargetIdentity,
    Target,
)
from .data import canonical_json, parse_json
from .hcap import HcapCatalog


MAX_METADATA_BYTES = 32 * 1024 * 1024
GIT_TIMEOUT_SECONDS = 10
MAX_GIT_OUTPUT_BYTES = 16 * 1024
Model = TypeVar("Model", bound=BaseModel)


class AuthorityGenerationError(ValueError):
    """Pinned generator inputs are invalid or mutually inconsistent."""


class DriftDetected(AuthorityGenerationError):
    """Checked-in generated bytes differ from the pinned inputs."""


class AdmissionProfileSource(AuthorityRecord):
    """Maintainer mapping input; the generator adds the measured identity."""

    schema_version: str = Field(pattern=r"^call-admission-source\.v1$")
    target: Target
    limits: AdmissionLimits
    entries: tuple[CallAdmissionEntry, ...] = Field(max_length=131072)

    @model_validator(mode="after")
    def _shape(self) -> AdmissionProfileSource:
        calls = tuple(entry.call for entry in self.entries)
        if len(calls) != len(set(calls)):
            raise ValueError("duplicate admission source call")
        if calls != tuple(sorted(calls)):
            raise ValueError("admission source calls must be sorted")
        return self


@dataclass(frozen=True)
class PinnedSyzkallerInputs:
    """Every filesystem input is required; no repository default is used."""

    checkout: Path
    expected_commit: str
    patch_series: Path
    build_root: Path
    build_manifest: Path
    call_table: Path
    target: str


@dataclass(frozen=True)
class InspectedSyzkaller:
    identity: SyzkallerTargetIdentity
    build_manifest: SyzkallerBuildManifest
    call_table: SyzkallerCallTable


def _read_regular(path: Path, *, max_bytes: int = MAX_METADATA_BYTES) -> bytes:
    try:
        info = path.lstat()
    except OSError as error:
        raise AuthorityGenerationError(f"cannot stat input: {path}") from error
    if path.is_symlink() or not stat.S_ISREG(info.st_mode):
        raise AuthorityGenerationError(f"input is not a regular file: {path}")
    if info.st_size > max_bytes:
        raise AuthorityGenerationError(f"metadata input is too large: {path}")
    try:
        data = path.read_bytes()
    except OSError as error:
        raise AuthorityGenerationError(f"cannot read input: {path}") from error
    if len(data) > max_bytes:
        raise AuthorityGenerationError(f"metadata input is too large: {path}")
    return data


def load_canonical_path(path: Path, model: type[Model]) -> Model:
    """Load one canonical JSON input without accepting alternate encodings."""

    data = _read_regular(path)
    try:
        parse_json(data)
        value = model.model_validate_json(data)
    except (ValueError, TypeError, RecursionError) as error:
        raise AuthorityGenerationError(
            f"invalid {model.__name__} input: {path}") from error
    if canonical_json(value) != data:
        raise AuthorityGenerationError(f"input is not canonical JSON: {path}")
    return value


def _hash_file(path: Path) -> str:
    try:
        info = path.lstat()
    except OSError as error:
        raise AuthorityGenerationError(f"cannot stat build file: {path}") from error
    if path.is_symlink() or not stat.S_ISREG(info.st_mode):
        raise AuthorityGenerationError(
            f"build input is not a regular file: {path}")
    digest = hashlib.sha256()
    try:
        with path.open("rb") as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
    except OSError as error:
        raise AuthorityGenerationError(f"cannot read build file: {path}") from error
    return digest.hexdigest()


def _run_git(checkout: Path, *arguments: str) -> bytes:
    """Run read-only Git inspection with bounded time and captured output."""

    environment = {
        **os.environ,
        "GIT_OPTIONAL_LOCKS": "0",
        "LC_ALL": "C",
    }
    try:
        with tempfile.TemporaryFile() as output:
            result = subprocess.run(
                ["git", "-c", "core.excludesFile=/dev/null", "-C",
                 str(checkout), *arguments],
                check=False, stdout=output, stderr=subprocess.STDOUT,
                timeout=GIT_TIMEOUT_SECONDS, env=environment)
            size = output.tell()
            if size > MAX_GIT_OUTPUT_BYTES:
                raise AuthorityGenerationError(
                    "git inspection output exceeded the limit")
            output.seek(0)
            data = output.read(MAX_GIT_OUTPUT_BYTES + 1)
    except subprocess.TimeoutExpired as error:
        raise AuthorityGenerationError("git inspection timed out") from error
    except OSError as error:
        raise AuthorityGenerationError(
            f"cannot inspect syzkaller checkout: {checkout}") from error
    if result.returncode != 0:
        message = data.decode("utf-8", errors="replace").strip()
        raise AuthorityGenerationError(
            f"cannot inspect syzkaller checkout: {message or checkout}")
    return data


def _git_head(checkout: Path) -> str:
    try:
        return _run_git(
            checkout, "rev-parse", "--verify", "HEAD^{commit}"
        ).decode("ascii").strip()
    except UnicodeDecodeError as error:
        raise AuthorityGenerationError(
            "git returned a non-ASCII commit identity") from error


def inspect_pinned_syzkaller(inputs: PinnedSyzkallerInputs) -> InspectedSyzkaller:
    """Measure and cross-check one caller-supplied checkout and build."""

    if re.fullmatch(r"[0-9a-f]{40}", inputs.expected_commit) is None:
        raise AuthorityGenerationError("expected commit must be a full lowercase SHA-1")
    if re.fullmatch(r"[a-z0-9_]+/[a-z0-9_]+", inputs.target) is None:
        raise AuthorityGenerationError("target must be an exact os/arch pair")
    try:
        checkout = inputs.checkout.resolve(strict=True)
        build_root = inputs.build_root.resolve(strict=True)
    except OSError as error:
        raise AuthorityGenerationError("checkout or build root does not exist") from error
    if not checkout.is_dir() or not build_root.is_dir():
        raise AuthorityGenerationError("checkout and build root must be directories")
    head = _git_head(checkout)
    if head != inputs.expected_commit:
        raise AuthorityGenerationError(
            f"syzkaller checkout is {head}, expected {inputs.expected_commit}")
    dirty = _run_git(
        checkout, "status", "--porcelain=v1", "-z",
        "--untracked-files=all", "--ignore-submodules=none")
    if dirty:
        raise AuthorityGenerationError(
            "syzkaller checkout has tracked or untracked worktree changes")

    patch_bytes = _read_regular(inputs.patch_series)
    patch_ref = hashlib.sha256(patch_bytes).hexdigest()
    manifest_bytes = _read_regular(inputs.build_manifest)
    call_table_bytes = _read_regular(inputs.call_table)
    manifest = load_canonical_path(inputs.build_manifest,
                                   SyzkallerBuildManifest)
    call_table = load_canonical_path(inputs.call_table, SyzkallerCallTable)
    if (manifest.syzkaller_commit != head
            or call_table.syzkaller_commit != head):
        raise AuthorityGenerationError(
            "build manifest or call table commit does not match checkout")
    if manifest.target != inputs.target or call_table.target != inputs.target:
        raise AuthorityGenerationError(
            "build manifest or call table target does not match requested target")
    if manifest.patch_series_sha256 != patch_ref:
        raise AuthorityGenerationError("patch series digest does not match manifest")

    for item in manifest.files:
        candidate = build_root.joinpath(*item.path.split("/"))
        try:
            resolved = candidate.resolve(strict=True)
            resolved.relative_to(build_root)
        except (OSError, ValueError) as error:
            raise AuthorityGenerationError(
                f"build manifest path escapes or is missing: {item.path}") from error
        if _hash_file(candidate) != item.artifact_ref:
            raise AuthorityGenerationError(
                f"build file digest mismatch: {item.path}")

    identity = SyzkallerTargetIdentity(
        syzkaller_commit=head,
        patch_series_sha256=patch_ref,
        build_manifest_sha256=hashlib.sha256(manifest_bytes).hexdigest(),
        call_table_sha256=hashlib.sha256(call_table_bytes).hexdigest(),
        target=inputs.target,
    )
    return InspectedSyzkaller(identity=identity, build_manifest=manifest,
                              call_table=call_table)


def generate_call_admission_profile(
        inputs: PinnedSyzkallerInputs, *, mapping_path: Path,
        hcap_path: Path) -> CallAdmissionProfile:
    """Generate a profile after resolving every call and capability."""

    inspected = inspect_pinned_syzkaller(inputs)
    source = load_canonical_path(mapping_path, AdmissionProfileSource)
    hcap = load_canonical_path(hcap_path, HcapCatalog)
    if source.target != inputs.target:
        raise AuthorityGenerationError(
            "admission source target does not match requested target")

    unresolved = sorted(set(entry.call for entry in source.entries)
                        - set(inspected.call_table.calls))
    if unresolved:
        raise AuthorityGenerationError(
            "admission source contains calls absent from pinned table: "
            + ", ".join(unresolved))
    by_id = {capability.id: capability for capability in hcap.capabilities}
    for capability_id in sorted({
            item for entry in source.entries for item in entry.capability_ids}):
        capability = by_id.get(capability_id)
        if capability is None:
            raise AuthorityGenerationError(
                f"admission source references unknown HCAP capability: {capability_id}")
        if ("stage1" not in capability.usable_stage
                or "agent_stage1" not in capability.usable_by):
            raise AuthorityGenerationError(
                f"HCAP capability is not usable by Stage 1: {capability_id}")

    return CallAdmissionProfile(
        identity=inspected.identity, limits=source.limits,
        entries=source.entries)


def write_or_check_profile(profile: CallAdmissionProfile, output: Path, *,
                           check: bool) -> str:
    """Write canonical bytes atomically, or fail without writing on drift."""

    expected = canonical_json(profile)
    digest = hashlib.sha256(expected).hexdigest()
    if check:
        try:
            actual = _read_regular(output)
        except AuthorityGenerationError as error:
            raise DriftDetected(f"generated profile is unavailable: {output}") from error
        if actual != expected:
            raise DriftDetected(
                f"generated call admission profile has drifted: {output}")
        return digest

    output.parent.mkdir(parents=True, exist_ok=True)
    try:
        with tempfile.NamedTemporaryFile(
                mode="wb", dir=output.parent,
                prefix=f".{output.name}.", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(expected)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, output)
    except OSError:
        try:
            temporary.unlink(missing_ok=True)
        except (OSError, UnboundLocalError):
            pass
        raise
    return digest
