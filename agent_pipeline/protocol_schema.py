"""ProtocolSchema path resolution for the Mutation Rule Compiler (08 §12).

The Proxy's tables (``tools/nfs-proxy/src/schema_*.c``) are generated by
``tools/nfs-proxy/schema/normalize.py`` from pinned XDR.  This module reads
the same normalized schemas from that normalizer and resolves a semantic
path to the node the Decoder would emit there, the way
``nfsp_schema_resolve`` (``src/schema.c``) does: the same naming
(``src/schema.h`` "SEMANTIC NAMING"), the same FOUND / AMBIGUOUS /
NOT_FOUND answers and the same node flags.  A ``schema_id`` is the digest of
its normalized schema, so a schema loaded here with the id a Proxy build
lists is the schema that build runs.

The Compiler needs a node's type to bind an enum name to its wire word in
that enum (03-nfs-proxy/04 §9: no reinterpretation) and its operation flag
to derive context dependencies (§10, §35).  Every other check is the
runtime's own validation, which the Compiler runs on the lowered set.
"""

from __future__ import annotations

import enum
import importlib.util
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

#: ``nfsp_schema_node`` flags (``src/schema.h``).
SN_OPERATION = 0x01
SN_ROOT = 0x02
SN_DISCRIMINANT = 0x04
SN_REPEATED = 0x08
SN_OPS_ARRAY = 0x10
SN_LIST_ELEMENT = 0x20

SCHEMA_ROOT = Path(__file__).resolve().parents[1] / "tools" / "nfs-proxy" / "schema"
#: The annotation of every family the Proxy links (``src/main.c``).
ANNOTATIONS = ("nfs4/nfs4.ann", "nfs3/nfs3.ann")

_WALK_MAX = 2 * 64 + 4


class Resolution(str, enum.Enum):
    FOUND = "found"
    NOT_FOUND = "not_found"
    AMBIGUOUS = "ambiguous"


@dataclass(frozen=True)
class Node:
    type: int
    flags: int
    root: str
    root_type: int
    #: The procedure number for a procedure root; None under an operation.
    proc: int | None


class ProtocolSchema:
    """One normalized ``nfsp-protocol-schema/1`` schema."""

    def __init__(self, data: dict) -> None:
        if data.get("format") != "nfsp-protocol-schema/1":
            raise ValueError("not a normalized ProtocolSchema")
        self.data = data
        self.schema_id: str = data["schema_id"]
        self.family: str = data["family"]
        self.program: int = data["program"]
        self.version: int = data["version"]
        self.minor: int | None = data["minor"]
        self.request_leaf, self.response_leaf = data["leaf"]
        self.types: list[dict] = data["types"]
        self.procedures: list[dict] = data["procedures"]

    # ------------------------------------------------------------ types

    def kind(self, t: int) -> str:
        return self.types[t]["kind"] if 0 <= t < len(self.types) else "void"

    def type_name(self, t: int) -> str:
        name = self.types[t].get("name") if 0 <= t < len(self.types) else None
        return name or f"<{self.kind(t)}>"

    def enum_value(self, t: int, name: str) -> int | None:
        """The wire word of ``name`` in enum type ``t``, or None."""
        if self.kind(t) != "enum":
            return None
        for label, value in self.types[t]["values"]:
            if label == name:
                return value
        return None

    def _arms(self, ty: dict) -> list[dict]:
        # The C table appends a default arm after the case arms.
        arms = list(ty["arms"])
        if ty.get("default") is not None:
            arms.append(ty["default"])
        return arms

    def _is_ops_union(self, ty: dict) -> bool:
        return ty["kind"] == "union" and ty.get("operations") in (
            "request", "response")

    # ------------------------------------------------------------ resolution

    def in_message(self, path: str, response: bool) -> bool:
        return path.startswith(self.family + (
            ".response." if response else ".request."))

    def resolve(self, response: bool, path: str
                ) -> tuple[Resolution, Node | None]:
        """``nfsp_schema_resolve``: a request (CALL) or response (REPLY)
        path to the one node it names."""
        mine = "response" if response else "request"
        leaf = self.response_leaf if response else self.request_leaf
        prefix = f"{self.family}.{mine}."
        found: list[Node] = []
        if not path.startswith(prefix):
            return Resolution.NOT_FOUND, None
        p = path[len(prefix):]

        for pr in self.procedures:
            rt = pr["res"] if response else pr["arg"]
            name = pr["name"]
            if rt is None or not p.startswith(name):
                continue
            rest = _component_at(p[len(name):], leaf)
            if rest is None:
                continue
            self._walk(found, mine, Node(rt, SN_ROOT, name, rt, pr["number"]),
                       rest, 0)

        for t, ty in enumerate(self.types):
            if not self._is_ops_union(ty) or ty["operations"] != mine:
                continue
            disc_name, disc_type = ty["disc"]
            for arm in self._arms(ty):
                branch = arm.get("branch")
                if not branch or not p.startswith(branch):
                    continue
                q = p[len(branch):]
                if not q:
                    found.append(Node(t, SN_ROOT | SN_OPERATION, branch, t,
                                      None))
                    continue
                rest = _component_at(q, disc_name)
                if rest is not None:
                    self._walk(found, mine, Node(
                        disc_type, SN_OPERATION | SN_DISCRIMINANT, branch, t,
                        None), rest, 0)
                if arm.get("type") is not None:
                    rest = _component_at(q, arm.get("component"))
                    if rest is not None:
                        self._walk(found, mine, Node(
                            arm["type"], SN_OPERATION, branch, t, None),
                            rest, 0)

        if not found:
            return Resolution.NOT_FOUND, None
        if any(n != found[0] for n in found[1:]):
            return Resolution.AMBIGUOUS, None
        return Resolution.FOUND, found[0]

    def _walk(self, found: list[Node], mine: str, at: Node, p: str,
              depth: int) -> None:
        if not 0 <= at.type < len(self.types) or depth > _WALK_MAX:
            return
        ty = self.types[at.type]
        # An operation is a root of its own, never a node of its container.
        if self._is_ops_union(ty):
            return
        inherit = at.flags & (SN_OPERATION | SN_REPEATED)
        kind = ty["kind"]
        if not p:
            flags = at.flags
            if kind in ("array_fixed", "array_var"):
                sub = self.types[ty["sub"]]
                if self._is_ops_union(sub) and sub["operations"] == mine:
                    flags |= SN_OPS_ARRAY
            found.append(Node(at.type, flags, at.root, at.root_type, at.proc))
            return

        def child(t: int, flags: int, rest: str) -> None:
            self._walk(found, mine, Node(t, flags, at.root, at.root_type,
                                         at.proc), rest, depth + 1)

        if kind == "struct":
            for name, t in ty["fields"]:
                rest = _component_at(p, name)
                if rest is not None:
                    child(t, inherit, rest)
        elif kind == "union":
            disc_name, disc_type = ty["disc"]
            rest = _component_at(p, disc_name)
            if rest is not None:
                child(disc_type, inherit | SN_DISCRIMINANT, rest)
            for arm in self._arms(ty):
                if arm.get("type") is None:
                    continue
                rest = _component_at(p, arm.get("component"))
                if rest is not None:
                    child(arm["type"], inherit, rest)
        elif kind in ("array_fixed", "array_var"):
            rest = _component_at(p, "[]")
            if rest is not None:
                child(ty["sub"], inherit | SN_REPEATED, rest)
        elif kind == "optional":
            rest = _component_at(p, "[]")
            if rest is not None:
                child(ty["sub"], inherit | SN_REPEATED | SN_LIST_ELEMENT,
                      rest)


def _component_at(p: str, c: str | None) -> str | None:
    """``component_at``: the rest of ``p`` after component ``c`` (".c", or
    "[]" for an element), or None.  Arm components may hold a dot, so the
    end is checked, not assumed."""
    if c is None:
        return None
    if c == "[]":
        return p[2:] if p.startswith("[]") else None
    if not p.startswith("." + c):
        return None
    rest = p[1 + len(c):]
    if rest and rest[0] not in ".[":
        return None
    return rest


def _load_normalizer(root: Path):
    spec = importlib.util.spec_from_file_location(
        "_nfsp_schema_normalize", root / "normalize.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@lru_cache(maxsize=4)
def _load(root: Path) -> tuple[ProtocolSchema, ...]:
    normalizer = _load_normalizer(root)
    schemas = []
    for ann in ANNOTATIONS:
        _, normalized = normalizer.normalize(str(root / ann))
        schemas.extend(ProtocolSchema(s) for s in normalized)
    return tuple(schemas)


def load_schemas(root: Path = SCHEMA_ROOT) -> dict[str, ProtocolSchema]:
    """Every ProtocolSchema the Proxy links, by schema_id, normalized from
    the pinned XDR under ``root``."""
    return {s.schema_id: s for s in _load(Path(root).resolve())}


